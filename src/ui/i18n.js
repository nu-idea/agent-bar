// Until the settings arrive: the language the window itself was started with.
let LANG = (navigator.language || '').toLowerCase().startsWith('ru') ? 'ru' : 'en';

function t(key, ...args) {
  const value = key in STRINGS[LANG] ? STRINGS[LANG][key] : key in STRINGS.en ? STRINGS.en[key] : key;
  return typeof value === 'function' ? value(...args) : value;
}

// Returns true when the language actually changed: the caller redraws what it built itself.
function setLang(lang) {
  const next = STRINGS[lang] ? lang : 'en';
  const changed = next !== LANG;
  LANG = next;
  document.documentElement.lang = LANG;
  for (const node of document.querySelectorAll('[data-t]')) node.textContent = t(node.dataset.t);
  for (const node of document.querySelectorAll('[data-t-title]')) node.title = t(node.dataset.tTitle);
  return changed;
}
